import assert from "node:assert/strict";
import {OntologyClient, SDKError} from "./dist/index.js";
const options={baseUrl:process.env.SDK_URL,tenantId:process.env.SDK_TENANT,tokenProvider:async()=>process.env.SDK_TOKEN};
const c=new OntologyClient(options);
const machine=await c.Machine.get("MCH-005");
assert.equal(typeof machine.properties.temperatureCelsius,"string");
const query=c.Machine.query().where(c.Machine.fields.temperatureCelsius.gt("20")).limit(2);
const first=await query.execute();assert.equal(first.items.length,2);assert.ok(first.next_cursor);
const second=await query.after(first.next_cursor).execute();assert.notEqual(first.items[0].object_id,second.items[0].object_id);
const status=await c.Machine.query().where(c.Machine.fields.operationalStatus.eq("RUNNING")).execute();assert.ok(status.items.length);
assert.equal((await c.Machine.related_locatedInFactory("MCH-005").execute()).items.length,1);
const params={machineId:"MCH-005",newStatus:"RUNNING",expectedRevision:machine.version};
assert.equal((await c.actions.UpdateMachineStatus.preview(params)).advisory,true);
const result=await c.actions.UpdateMachineStatus.execute(params,"typescript-acceptance");
assert.equal(result.execution_id,(await c.actions.UpdateMachineStatus.execute(params,"typescript-acceptance")).execution_id);
await assert.rejects(c.Machine.patch("MCH-005",{machineName:"stale"},machine.version),e=>e instanceof SDKError && e.status===409);
const bad=new OntologyClient({...options,tokenProvider:async()=>"invalid"});
await assert.rejects(bad.Machine.get("MCH-005"),e=>e instanceof SDKError && e.status===401);
const foreign=new OntologyClient({...options,tenantId:"00000000-0000-0000-0000-000000000099"});
await assert.rejects(foreign.Machine.get("MCH-005"),e=>e instanceof SDKError && e.status===403);
